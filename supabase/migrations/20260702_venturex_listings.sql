-- ─── RLS ────────────────────────────────────────────────────
ALTER TABLE public.venturex_listed_companies ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_read_listings" ON public.venturex_listed_companies;
CREATE POLICY "authenticated_read_listings" ON public.venturex_listed_companies
  FOR SELECT TO authenticated USING (status = 'active');

DROP POLICY IF EXISTS "admin_all_listings" ON public.venturex_listed_companies;
CREATE POLICY "admin_all_listings" ON public.venturex_listed_companies
  FOR ALL TO authenticated USING (
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

GRANT SELECT ON public.venturex_listed_companies TO authenticated;

-- ─── Interest tracking ──────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.venturex_interest (
  id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id         UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  company_id      UUID REFERENCES public.venturex_listed_companies(id) ON DELETE CASCADE,
  message         TEXT,
  investment_range TEXT,
  created_at      TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(user_id, company_id)
);

ALTER TABLE public.venturex_interest ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "own_interest" ON public.venturex_interest;
CREATE POLICY "own_interest" ON public.venturex_interest
  FOR ALL TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

GRANT ALL ON public.venturex_interest TO authenticated;

